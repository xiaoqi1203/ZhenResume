def seed_if_empty(db: Session, *, force: bool = False) -> int:
    """知识库为空时写入种子数据；force=True 时全量重建。"""
    existing = db.execute(select(func.count()).select_from(KnowledgeDoc)).scalar_one()
    if existing and not force:
        return 0

    if force and existing:
        for doc in db.execute(select(KnowledgeDoc)).scalars().all():
            db.delete(doc)
        db.flush()

    count = 0
    for spec in SEED_DOCS:
        doc = KnowledgeDoc(
            scope=spec["scope"],
            role_family=spec.get("role_family"),
            doc_type=spec.get("doc_type"),
            title=spec["title"],
            content=spec["content"],
            doc_metadata={"seeded": True},
        )
        db.add(doc)
        db.flush()
        rag.index_document(db, doc)
        count += 1

    db.commit()
    return count
