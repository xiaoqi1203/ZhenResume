PER_GROUP = 8


def build_resume(base: dict, *, literal: list[str], equiv: list[str], real_gap: list[str], index: int) -> str:
    """按三种状态拼一份简历：字面写法（含目标词）+ 等价措辞 + 中性内容（真缺失项不出现）。"""
    lines = [
        base["name"],
        f"后端开发工程师 | 杭州 | 138-0000-{index:04d} | dev{index}@example.com",
        "",
        "工作经历",
        f"{base['company']} | 后端开发工程师    {base['start']} - {base['end']}",
    ]
    for kw in literal:
        lines.append(f"- {DIMENSIONS[kw]['literal']}")
    for kw in equiv:
        lines.append(f"- {DIMENSIONS[kw]['equiv']}")
    for i in range(len(real_gap)):
        lines.append(f"- {NEUTRAL_LINES[i % len(NEUTRAL_LINES)]}")
    lines += ["", "专业技能", SKILL_LINE, "", "教育经历", base["school"]]
    return "\n".join(lines)


def plan() -> list[dict]:
    """展开四组配方：每组 8 份，配方循环使用，因此**组内也有覆盖度差异**。"""
    out: list[dict] = []
    idx = 0
    for group in ("A", "B", "C", "D"):
        recipes = GROUPS[group]
        for k in range(PER_GROUP):
            literal, equiv = recipes[k % len(recipes)]
            covered = set(literal) | set(equiv)
            real_gap = [item for item in DIMENSION_ORDER if item not in covered]
            out.append(
                {
                    "record_id": f"sort_{group}{k:02d}",
                    "group": group,
                    "base_index": idx % len(BASES),
                    "literal": literal,
                    "equiv": equiv,
                    "real_gap": real_gap,
                }
            )
            idx += 1
    return out
